def esc(s):
    # keep pre-escaped &amp;
    s = s.replace("&amp;", "\x00").replace("&", "&amp;").replace("\x00", "&amp;")
    s = s.replace("<", "&lt;").replace("'", "\\'").replace('"', '\\"').replace("\n", "\\n")
    if s.startswith("@") or s.startswith("?"): s = "\\" + s
    return s
